    /** Resolve a runtime mode to the root palette bytes used by Palette::fromBytes(). */
    public static function for(PaletteMode $mode): string
    {
        return match ($mode) {
            PaletteMode::Color => self::COLOR,
            PaletteMode::ClassicColor => self::CLASSIC_COLOR,
            PaletteMode::BlackWhite => self::BLACK_WHITE,
            PaletteMode::Monochrome => self::MONOCHROME,
        };
    }
}
